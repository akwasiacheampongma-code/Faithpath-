#!/usr/bin/env python3
"""Offline, deterministic transfer of the frozen approved FaithPath NT catalog.

No question generation, editorial normalization, network, Excel evaluation or
external Git checkout is involved. --check verifies every generated byte.
"""
import argparse
import gzip
import hashlib
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "content/faithpath-nt"
SNAPSHOT = "a519ce898fa33907b07d5ac7a585595127556183"
EXPECTED = {
    "data/stories.json": "f9fc48a97ecb129eaed0289cf94afa7c747f15afe381fbe6241e67fac5ec04cd",
    "reports/nt-quiz-final/master.json": "f322bbe0b8214839faf4b6f5a0b994f441e745678ffa83669c3e528f62fdce56",
    "reports/nt-quiz-final/manifest.json": "d6473e899e31f0340f61d0a59c1a2a3fa19de43962a415094df5c7ac1bbaaf14",
    "reports/nt-quiz-final/acceptance.json": "6d9a0de11b10abe0f3920aafdc346cbe0632b6f5861d53cecf9ea3108bd2b56b",
    "data/nt-quiz-status.json": "8b3e37a97e15ac9b3d6856cd1b45f58c83dae1dad2486d84061a28ec44c98c7d",
    "NT_QUIZ_FINAL_IMPORT_REPORT.md": "b2b36f3533eca7d15b7cecb89f13419a63645d6a0fb9050a51f0506d77438725",
    "scripts/quiz-reference-ranges.mjs": "0bcb56804f0944677c6d6e8f7c73aef7fa66592e8a078861c2d44323648e1433",
}
QUESTION_KEYS = {"faithpath_id", "q", "a", "c", "ref", "x"}
UNIT_KEYS = {
    "id", "kind", "book", "chapter", "from", "to", "title", "ref", "desc",
    "reflection", "reflectionStatus", "verification", "questions",
}


def require(condition, label):
    if not condition:
        raise ValueError(label)


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def encode(value, *, canonical=False):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"),
                      sort_keys=canonical).encode("utf-8")


def nonempty(value):
    return isinstance(value, str) and bool(value.strip())


def integer(value):
    return type(value) is int


def frozen_sources():
    provenance = json.loads((SOURCE / "provenance.json").read_bytes())
    require(provenance["source_snapshot"] == SNAPSHOT, "source snapshot changed")
    files = provenance["files"]
    require(len(files) == len(EXPECTED), "frozen source count")
    require({entry["source_path"] for entry in files} == set(EXPECTED), "source paths")
    result = {}
    for entry in files:
        path = entry["source_path"]
        require(entry["archive"] == "source/" + path + ".gz", "archive path")
        compressed = (SOURCE / entry["archive"]).read_bytes()
        require(compressed[:2] == b"\x1f\x8b" and compressed[4:8] == b"\0" * 4,
                "gzip format/mtime: " + path)
        require(len(compressed) == entry["archive_bytes"], "archive bytes: " + path)
        require(digest(compressed) == entry["archive_sha256"], "archive digest: " + path)
        raw = gzip.decompress(compressed)
        require(len(raw) == entry["bytes"], "source bytes: " + path)
        require(digest(raw) == entry["sha256"] == EXPECTED[path], "source digest: " + path)
        result[path] = raw
    return result


def parse_references(text, books):
    """Faithful Python port of the frozen scripts/quiz-reference-ranges.mjs.

    The tests also run that original JavaScript parser over all 1,300 strings.
    Semicolons/periods remain separate ranges, including single-chapter books.
    """
    names = sorted(books, key=lambda book: len(book["name"]), reverse=True)
    definition = next((book for book in names if text.startswith(book["name"] + " ")), None)
    require(definition is not None, "unknown reference book")
    part = text[len(definition["name"]) + 1:]
    if "," in part:
        match = re.fullmatch(r"(\d+),(.+)", part)
        require(match is not None, "invalid chapter reference")
        chapter, part = int(match[1]), match[2]
    else:
        require(definition["chapters"] == 1, "reference missing chapter")
        chapter = 1
    result = []
    for segment in re.split(r"[;.]", part):
        match = re.fullmatch(r"(\d+)(?:[–-](\d+))?", segment.strip())
        require(match is not None, "invalid verse reference")
        start, end = int(match[1]), int(match[2] or match[1])
        require(1 <= chapter <= definition["chapters"] and 1 <= start <= end,
                "invalid reference bounds")
        result.append({"book": definition["code"], "chapter": chapter,
                       "from": start, "to": end})
    return result


def generate():
    raw = frozen_sources()
    stories = json.loads(raw["data/stories.json"])
    master = json.loads(raw["reports/nt-quiz-final/master.json"])
    manifest = json.loads(raw["reports/nt-quiz-final/manifest.json"])
    require(manifest["imported_stories_sha256"] == EXPECTED["data/stories.json"], "manifest stories")
    require(manifest["normalized_sha256"] == EXPECTED["reports/nt-quiz-final/master.json"], "manifest master")
    require(manifest["imported_status_sha256"] == EXPECTED["data/nt-quiz-status.json"], "manifest status")
    require(manifest["source_sha256"] == "ddb5e9c5832a1aa60e5329621c6a0c92002cd1b879177c5b39027344cce5c199", "manifest workbook")
    require(master["schema_version"] == 1 and master["sheet"] == "FAITHPATH_IMPORT", "master sheet")
    rows = master["rows"]
    require(len(rows) == 1300, "master rows")
    canonical = json.loads((ROOT / "src/data/catalog.json").read_bytes())
    books = [book for book in canonical if book["testament"] == "NT"]
    require(len(books) == 27 and sum(book["chapters"] for book in books) == 260, "NT canon")
    bible = json.loads((ROOT / "src/data/bible.json").read_bytes())
    expected_chapters = [(book["code"], chapter, book["name"])
                         for book in books for chapter in range(1, book["chapters"] + 1)]
    units = [unit for unit in stories if unit.get("kind") == "chapter-quiz"]
    require(len(stories) == 312 and sum(len(unit["questions"]) for unit in stories) == 1560,
            "mixed source totals")
    require(len(units) == 260, "NT units")
    chapters, chapter_index, ids = [], [], []
    reference_count = multiple_count = one_chapter_count = 0
    correct_indices = Counter()
    for position, unit in enumerate(units):
        code, chapter, name = expected_chapters[position]
        require(set(unit) == UNIT_KEYS, "unit keys")
        require(unit["id"] == 10000 + position and integer(unit["id"]), "legacy ID order")
        require(unit["book"] == code and integer(unit["chapter"]) and unit["chapter"] + 1 == chapter,
                "canonical chapter order / zero-based source chapter")
        for field in ["title", "ref", "desc", "reflection", "reflectionStatus", "verification"]:
            require(nonempty(unit[field]), "unit field: " + field)
        verse_numbers = {verse["n"] for verse in bible[code][str(chapter)]}
        require(integer(unit["from"]) and integer(unit["to"]) and unit["from"] <= unit["to"] and
                all(n in verse_numbers for n in range(unit["from"], unit["to"] + 1)), "unit verses")
        require(len(unit["questions"]) == 5, "five questions per chapter")
        require(len({question["q"] for question in unit["questions"]}) == 5, "distinct chapter prompts")
        questions = []
        for order, question in enumerate(unit["questions"]):
            require(set(question) == QUESTION_KEYS, "question keys")
            number = position * 5 + order
            expected_id = "FP-" + str(261 + number).zfill(4)
            require(question["faithpath_id"] == expected_id, "contiguous question IDs/order")
            ids.append(expected_id)
            require(all(nonempty(question[field]) for field in ["q", "ref", "x"]), "question text fields")
            require(isinstance(question["a"], list) and len(question["a"]) == 4 and
                    all(nonempty(option) for option in question["a"]) and len(set(question["a"])) == 4,
                    "four distinct nonempty options")
            require(integer(question["c"]) and 0 <= question["c"] <= 3, "correct index")
            row = rows[number]
            require(row["FP_ID"] == expected_id and row["book_key"] == code and row["book_name"] == name and
                    row["chapter"] == chapter and row["question_order"] == order + 1, "master identity/order")
            require(question["q"] == row["question"] and question["a"] == [row[f"option_{i}"] for i in range(4)] and
                    question["c"] == row["correct_index"] and question["ref"] == row["reference"] and
                    question["x"] == row["explanation"], "all question fields must equal final master verbatim")
            require(row["correct_answer"] == question["a"][question["c"]], "master correct answer")
            require(row["qa_status"] == row["approval"] == "FREIGEGEBEN" and row["import_ready"] == "JA",
                    "master release flags")
            ranges = parse_references(question["ref"], books)
            for reference in ranges:
                require(reference["book"] == code and reference["chapter"] == chapter, "reference context")
                require(all(n in verse_numbers for n in range(reference["from"], reference["to"] + 1)),
                        "every referenced OLIVA verse must exist")
            reference_count += len(ranges)
            multiple_count += len(ranges) > 1
            one_chapter_count += "," not in question["ref"]
            correct_indices[question["c"]] += 1
            snapshot = {"id": expected_id, "book": code, "chapter": chapter, "legacyUnitId": unit["id"],
                        "prompt": question["q"], "options": question["a"], "correctIndex": question["c"],
                        "referenceText": question["ref"], "referenceRanges": ranges, "explanation": question["x"]}
            questions.append({**snapshot, "hash": digest(encode(snapshot, canonical=True))})
        entry = {"key": f"{code}:{chapter}", "book": code, "chapter": chapter, "legacyUnitId": unit["id"],
                 "title": unit["title"]}
        chapter_index.append({**entry, "questionCount": 5})
        chapters.append({**entry, "referenceText": unit["ref"], "description": unit["desc"],
                         "reflection": unit["reflection"], "questions": questions})
    require(len(ids) == len(set(ids)) == 1300, "question ID uniqueness/count")
    require((reference_count, multiple_count, one_chapter_count) == (1304, 4, 20), "reference totals")
    catalog = encode({"chapters": chapters}) + b"\n"
    index = encode({"books": [{"code": book["code"], "name": book["name"], "chapters": book["chapters"],
                               "questions": book["chapters"] * 5} for book in books],
                    "chapters": chapter_index}) + b"\n"
    evidence = {
        "status": "PASS", "source_snapshot": SNAPSHOT,
        "validation": "Reproducible offline importer assertions; not new browser, device or theological acceptance.",
        "source_hashes": EXPECTED,
        "counts": {"mixed_units": len(stories), "mixed_questions": 1560,
                   "excluded_story_units": len(stories) - len(units), "excluded_story_questions": 260,
                   "books": len(books), "chapters": len(chapters), "questions": len(ids), "questions_per_chapter": 5,
                   "reference_ranges": reference_count, "questions_with_multiple_ranges": multiple_count,
                   "single_chapter_references_without_chapter_number": one_chapter_count},
        "question_ids": {"first": ids[0], "last": ids[-1], "contiguous_unique_in_source_order": True},
        "legacy_unit_ids": {"first": units[0]["id"], "last": units[-1]["id"], "contiguous_unique_in_source_order": True},
        "correct_index_distribution": {str(i): correct_indices[i] for i in range(4)},
        "checks": {"all_fields_and_option_order_equal_final_master": True, "master_correct_answers_match_indices": True,
                   "all_master_rows_released": True, "canonical_chapter_order_complete": True,
                   "zero_based_source_chapters_converted_once": True, "all_referenced_verses_exist": True,
                   "frozen_source_hashes_verified": True},
        "outputs": {"src/data/nt-catalog.json": {"bytes": len(catalog), "sha256": digest(catalog)},
                    "src/data/nt-index.json": {"bytes": len(index), "sha256": digest(index)}},
        "hash_contract": "sha256(UTF-8 canonicalJson(all NtQuestionSnapshot fields)); keys sorted recursively, arrays and strings preserved, hash excluded",
        "rights": "User-commissioned integration; original FaithPath content rights retained. No extension of OLIVA MIT license.",
        "limits": ["No question content duplicated in this evidence.", "No Excel formula recalculation or new editorial/theological approval."]}
    return {ROOT / "src/data/nt-catalog.json": catalog, ROOT / "src/data/nt-index.json": index,
            ROOT / "docs/evidence/nt-catalog/ingestion/catalog-check.json":
                json.dumps(evidence, ensure_ascii=False, indent=2).encode("utf-8") + b"\n"}, evidence


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files without writing")
    args = parser.parse_args()
    outputs, evidence = generate()
    for path, data in outputs.items():
        if args.check:
            require(path.is_file() and path.read_bytes() == data, "generated output differs: " + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(json.dumps({"status": "PASS", "mode": "check" if args.check else "write", **evidence["counts"],
                      "catalog_sha256": evidence["outputs"]["src/data/nt-catalog.json"]["sha256"]}))


if __name__ == "__main__":
    main()
